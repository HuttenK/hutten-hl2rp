function U.IconName(value)
 value=tostring(value or ""):utf8lower()
 if glyphs[value] then return value end
 for _,entry in ipairs(aliases) do
  for i=2,#entry do if value:find(entry[i],1,true) then return entry[1] end end
 end
 return "seal"
end
function U.Icon(name,x,y,size,color)
 name=glyphs[name] and name or U.IconName(name)
 local glyph=glyphs[name] or glyphs[U.IconName(name)]
 surface.SetDrawColor(color or U.accent)
 local unit=size/24
 for _,path in ipairs(glyph) do
  for i=1,#path-2,2 do
   surface.DrawLine(x+path[i]*unit,y+path[i+1]*unit,x+path[i+2]*unit,y+path[i+3]*unit)
  end
 end
end
