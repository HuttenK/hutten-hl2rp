// Usage: node tools/build-field-shaders.cjs <ShaderCompile.exe> <build directory on E:>
const fs = require('fs'), path = require('path'), cp = require('child_process'), crypto = require('crypto');
const [compiler, out] = process.argv.slice(2);
if (!compiler || !out) throw Error('Compiler and external build directory required');
const root = path.resolve(__dirname, '..');
fs.mkdirSync(out, {recursive:true});
const names = ['field_world', 'field_nvg', 'field_lens', 'field_bright', 'field_glow'];
for (const n of names) fs.copyFileSync(path.join(__dirname,'shaders',n+'_ps2x.hlsl'),path.join(out,n+'_ps2x.hlsl'));
const result = cp.spawnSync(compiler,['-ver','20b','-force','-shaderpath',out,...names.map(n=>path.join(out,n+'_ps2x.hlsl'))],{encoding:'utf8'});
fs.writeFileSync(path.join(out,'compile.log'), result.stdout+'\n'+result.stderr);
if (result.status !== 0 || /error (X\d+|:)/i.test(result.stdout+result.stderr)) throw Error(result.stdout+result.stderr);
const shaders = names.map(n=>fs.readFileSync(path.join(out,'shaders/fxc',n+'_ps20b.vcs')));
for (const bytes of shaders) if (bytes.length < 48 || bytes.readUInt32LE(0)!==6) throw Error('Invalid VCS output');
const version = crypto.createHash('sha256').update(Buffer.concat(shaders)).digest('hex').slice(0,12);
const u32 = n=>{const b=Buffer.alloc(4);b.writeUInt32LE(n>>>0);return b;};
const u64 = n=>{const b=Buffer.alloc(8);b.writeBigUInt64LE(BigInt(n));return b;};
const str = s=>Buffer.from(s+'\0');
function crc32(buf) {let c=0xffffffff;for (const b of buf) {c^=b;for(let k=0;k<8;k++) c=(c>>>1)^((c&1)?0xedb88320:0);}return (c^0xffffffff)>>>0;}
const stem = 'field_'+version;
const paths = names.map(n=>'shaders/fxc/'+stem+'_'+n.replace('field_','')+'_ps20b.vcs');
const header = [Buffer.from('GMAD'),Buffer.from([3]),u64(0),u64(0),str(''),str('Fieldlink shaders '+version),str('{}'),str('Legends'),u32(1)];
shaders.forEach((b,i)=>header.push(u32(i+1),str(paths[i]),u64(b.length),u32(crc32(b))));
header.push(u32(0),...shaders);
const body=Buffer.concat(header), gma=Buffer.concat([body,u32(crc32(body))]);
fs.writeFileSync(path.join(out,stem+'.gma'),gma);
const lua = `-- Generated by tools/build-field-shaders.cjs; edit tools/shaders/*.hlsl instead.\nreturn {version = "${version}", stem = "${stem}", payload = [[${gma.toString('base64')}]]}\n`;
fs.writeFileSync(path.join(root,'ixhl2rp/plugins/zz_legends_visuals/cl_shader_payload.lua'),lua);
fs.writeFileSync(path.join(out,'manifest.json'),JSON.stringify({version,paths,bytes:gma.length,sha256:crypto.createHash('sha256').update(gma).digest('hex')},null,2));
console.log(`Built ${paths.length} validated VCS shaders; embedded GMA ${gma.length} bytes; version ${version}`);
