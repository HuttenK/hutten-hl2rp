// Build a read-only wiring manifest from the installed compiled map, never edit the addon.
const fs = require('node:fs'), path = require('node:path'), zlib = require('node:zlib');
const root = path.resolve(__dirname, '..');
const directory = path.join(root, 'ixhl2rp/plugins/map_keycards');
const maps = {};
for (const suffix of ['us', 'fr']) {
  const map = 'rp_zone_tsade_v1f_' + suffix;
  const bsp = fs.readFileSync(path.join(root, '.runtime/tsade-door-audit', map + '.bsp'));
  if (bsp.toString('ascii',0,4) !== 'VBSP' || bsp.readInt32LE(4) !== 20) throw Error('Unexpected BSP');
  const raw = bsp.subarray(bsp.readInt32LE(8), bsp.readInt32LE(8) + bsp.readInt32LE(12));
  if (raw.toString('ascii',0,4) === 'LZMA') throw Error('Decompress entity lump before rebuilding');
  const tokens = [...raw.toString('utf8').matchAll(/"((?:\\.|[^"\\])*)"|([{}])/g)];
  const es = []; let current;
  for (let i=0;i<tokens.length;i++) {
    const t=tokens[i];
    if(t[2]==='{') current={kv:{},outputs:[]};
    else if(t[2]==='}') {es.push(current);current=null;}
    else {const key=t[1],v=tokens[++i][1];current.kv[key]=v;if(/^On[A-Z]/.test(key)){const [target,input]=v.split(v.includes('\x1b')?'\x1b':',');current.outputs.push({target,input});}}
  }
  const names=new Map();
  for(const e of es){const n=e.kv.targetname;if(n){if(!names.has(n))names.set(n,[]);names.get(n).push(e);}}
  const door=e=>['func_door','func_door_rotating','prop_door_rotating','func_movelinear'].includes(e.kv.classname);
  const button=e=>['func_button','func_rot_button'].includes(e.kv.classname);
  const relevant=es.filter(e=>door(e)||button(e));
  const parent=new Map(relevant.map(e=>[e,e]));
  const find=e=>parent.get(e)===e?e:find(parent.get(e));
  const union=(a,b)=>parent.set(find(a),find(b));
  const master=e=>e.kv.classname==='func_rot_button'||e.outputs.some(o=>o.target.includes('*'))||/^(scpdoors_lever|lever_|d_blast_door_lever|blast_lumos)/.test(e.kv.targetname||'');
  function targets(name){
    if(!name.includes('*'))return names.get(name)||[];
    const re=new RegExp('^'+name.split('*').map(s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('.*')+'$');
    return es.filter(e=>e.kv.targetname&&re.test(e.kv.targetname));
  }
  function trace(e,visited=new Set()) {
    if(visited.has(e))return [];visited.add(e);
    const out=[];
    for(const o of e.outputs)for(const t of targets(o.target)) {
      if(door(t)&&/^(Open|Close|Toggle|SetPosition)$/i.test(o.input))out.push(t);
      else if(t.kv.classname==='logic_relay'&&o.input==='Trigger'&&/elevator/i.test(e.kv.targetname||''))out.push(...trace(t,visited));
    }
    return out;
  }
  for(const e of relevant.filter(button))if(!master(e))for(const d of trace(e))union(e,d);
  const groups=new Map();
  for(const e of relevant){const r=find(e);if(!groups.has(r))groups.set(r,[]);groups.get(r).push(e);}
  const records=[];
  for(const members of groups.values()) {
    const ids=members.map(e=>Number(e.kv.hammerid)).sort((a,b)=>a-b);
    const controls=members.filter(button);
    const name=(members.find(e=>door(e)&&e.kv.targetname)||members.find(e=>e.kv.targetname)||members[0]).kv.targetname||('Door '+ids[0]);
    records.push({id:String(ids[0]),name,kind:members.some(e=>/elevator/i.test(e.kv.targetname||''))?'elevator':controls.some(master)?'master':members.some(door)?'door':'control',
      members:members.map(e=>({id:e.kv.hammerid,class:e.kv.classname,model:e.kv.model||'',name:e.kv.targetname||'',origin:(e.kv.origin||'0 0 0').split(/\s+/).map(Number),control:button(e)}))});
  }
  records.sort((a,b)=>Number(a.id)-Number(b.id));
  maps[map]={crc:String(zlib.crc32(raw)),groups:records};
  console.log(map, records.length,'groups;',relevant.length,'entities; largest',Math.max(...records.map(g=>g.members.length)));
}
// Lua long strings preserve JSON exactly and do not execute map data.
fs.mkdirSync(directory,{recursive:true});
fs.writeFileSync(path.join(directory,'sv_tsade.lua'),'-- Generated by tools/build-tsade-access.cjs from inspected BSP entity wiring.\n-- Trusted static manifest: lift JSON key limit and preserve string keys.\nreturn util.JSONToTable([====[\n'+JSON.stringify(maps)+'\n]====], true, true)\n');
fs.writeFileSync(path.join(root,'.runtime/tsade-door-audit/access-manifest.json'),JSON.stringify(maps,null,2));
